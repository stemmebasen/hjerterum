const WEEKDAYS_SHORT: Record<string, string> = { man: "Mon", tir: "Tue", ons: "Wed", tor: "Thu", fre: "Fri", lør: "Sat", søn: "Sun" };
const MONTHS: Record<string, string> = { januar: "January", februar: "February", marts: "March", april: "April", maj: "May", juni: "June", juli: "July", august: "August", september: "September", oktober: "October", november: "November", december: "December" };
const MONTHS_SHORT: Record<string, string> = { jan: "Jan", feb: "Feb", mar: "Mar", apr: "Apr", maj: "May", jun: "Jun", jul: "Jul", aug: "Aug", sep: "Sep", okt: "Oct", nov: "Nov", dec: "Dec" };

const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const W = "(?:[Mm]andag|[Tt]irsdag|[Oo]nsdag|[Tt]orsdag|[Ff]redag|[Ll]ørdag|[Ss]øndag)";
const WS = "(?:[Mm]an|[Tt]ir|[Oo]ns|[Tt]or|[Ff]re|[Ll]ør|[Ss]øn)\\.?";
const M = "(?:januar|februar|marts|april|maj|juni|juli|august|september|oktober|november|december)";
const MS = "(?:jan|feb|mar|apr|maj|jun|jul|aug|sep|okt|nov|dec)\\.?";
const TIME = "\\d{1,2}(?:\\.\\d{2})?";
/** A Danish date or time inside a text ("Søndag 11. oktober", "Søn. 11. okt.", "kl. 15.30–18.00", "til 18.30"). */
const DATEISH = new RegExp(`(?:${W}|${WS})(?= \\d)|\\b\\d{1,2}\\. (?:${M}|${MS})(?: \\d{4})?|\\bkl\\. ${TIME}(?:–${TIME})?|\\btil ${TIME}\\b|\\b\\d{1,2}\\.\\d{2}–\\d{1,2}\\.\\d{2}\\b`, "g");
const time = (s: string) => s.replace(/(\d{1,2})\.(\d{2})/g, "$1:$2");

/** Dates and times in English ("Sunday 11 October", "Sun 11 Oct 15:30", "15:30–18:00", "until 18:30"). */
export function englishDates(text: string): string {
  return text.replace(DATEISH, (part: string) => {
    let m = new RegExp(`^(${W})$`).exec(part);
    if (m) { const en = WEEKDAYS[m[1]!.toLowerCase()]!; return m[1]![0] === m[1]![0]!.toUpperCase() ? en : en; }
    m = new RegExp(`^(${WS})$`).exec(part);
    if (m) return WEEKDAYS_SHORT[m[1]!.replace(".", "").toLowerCase()]!;
    m = /^(\d{1,2})\. ([a-zæøå]+)\.?( \d{4})?$/.exec(part);
    if (m) return `${m[1]} ${MONTHS[m[2]!] ?? MONTHS_SHORT[m[2]!] ?? m[2]}${m[3] ?? ""}`;
    m = /^kl\. (.+)$/.exec(part);
    if (m) return time(m[1]!);
    m = /^til (.+)$/.exec(part);
    if (m) return `until ${time(m[1]!)}`;
    return time(part);
  });
}
